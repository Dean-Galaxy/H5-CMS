#!/usr/bin/env python3
"""06 fixed-candidate delta only: mobile definition lists, return labels and cover hierarchy."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parents[2]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('scenario', choices=['release-layout', 'cover-alignment'])
p.add_argument('--candidate', required=True, help='Full immutable application SHA supplied by 00')
a = p.parse_args()
if len(a.candidate) != 40 or any(c not in '0123456789abcdef' for c in a.candidate):
    raise SystemExit('Full candidate SHA required.')
ws = json.loads((ROOT / '.runtime/workspace.json').read_text())
assert Path(ws['root']).resolve() == ROOT and ws['port'] not in [8206, 8303]
paths = ['h5-platform/app', 'h5-platform/config', 'h5-platform/resources', 'h5-platform/public', 'h5-platform/routes', 'h5-platform/database', 'h5-platform/bootstrap', 'h5-platform/composer.json', 'h5-platform/composer.lock']
if subprocess.check_output(['git', 'diff', a.candidate, '--', *paths], cwd=ROOT):
    raise SystemExit('Running application must match fixed candidate.')
changes = subprocess.check_output(['git','diff','--name-only','658f407',a.candidate,'--',*paths],cwd=ROOT,text=True).splitlines()
expected = {'h5-platform/public/content/admin.css', 'h5-platform/public/content/admin.js', 'h5-platform/resources/views/content/settings.blade.php'}
if set(changes) != expected:
    raise SystemExit('Unexpected application delta; coordinate scope with 00.')
owner = ROOT / '.runtime/content/preview-account.json'
if owner.stat().st_mode & 0o077:
    raise SystemExit('Private 0600 own Owner required.')
module = os.environ.get('H5_PLAYWRIGHT_MODULE')
if not module or not Path(module).exists():
    raise SystemExit('Use existing local H5_PLAYWRIGHT_MODULE.')
source = ROOT / 'h5-platform/tests/Feature/Content/Support' / (a.scenario+'.browser.cjs')
original = source.read_text()
if subprocess.check_output(['git','show',a.candidate+':'+str(source.relative_to(ROOT))],cwd=ROOT,text=True) != original:
    raise SystemExit('Module test source differs from fixed candidate.')
run = ROOT / '.runtime/06-f09' / a.candidate[:12] / a.scenario
run.mkdir(parents=True,exist_ok=True,mode=0o700)
script = original.replace("runtime+'/"+a.scenario+"'", json.dumps(str(run)))
# Use our already generated media; no imports from any other workspace.
(ROOT/'.runtime/content/ui-1.srt').write_text('1\n00:00:01,000 --> 00:00:01,900\nWe meet again.\n')
(ROOT/'.runtime/content/cover.jpg').write_bytes((ROOT/'.runtime/content/ui-cover.png').read_bytes())
script = script.replace("'02 两列布局复验 '+Date.now()", "'逆光之约'").replace("'02 封面位置复验 '+Date.now()", "'逆光之约'")
script = script.replace("'Content layout verification'", "'Into the Light'").replace("'Cover alignment verification'", "'Into the Light'")
# Same approved prototype date, required to remain future for this fixed execution.
date = '2026-10-24T00:00'
if datetime.now(timezone.utc) >= datetime.fromisoformat(date+'+08:00'):
    raise SystemExit('Prototype date expired; coordinate a new matching date on both sides.')
script = script.replace("new Date(Date.now()+3*86400000+8*3600000).toISOString().slice(0,16)", repr(date))
if a.scenario == 'cover-alignment':
    script = script.replace("const cover=await upload('cover',runtime+'/ui-cover.png')", "const cover=await upload('cover',runtime+'/cover.jpg')")
    script = script.replace("await choose(runtime+'/ui-cover.png')", "await choose({name:'cover_new.jpg',mimeType:'image/png',buffer:fs.readFileSync(runtime+'/ui-cover.png')})")
script = script.replace('Real 02 staff/API/synthetic media only.', 'Real 06 isolated staff/API/synthetic media only.').replace('No 06/07 service touched.', 'Only new 06 8377 touched; old 8206/8303 and 07 untouched.').replace('Real 02 API and generated PNG;', 'Real 06 isolated API and generated PNG;').replace('No original assets or 06/07 data.', 'No original assets or old 8206/8303/07 data.')
prepared = run / 'run.cjs'
prepared.write_text(script);prepared.chmod(0o600)
meta = {'candidate':a.candidate,'checkoutHead':subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),'scenario':a.scenario,'source':str(source.relative_to(ROOT)),'sourceSha256':hashlib.sha256(original.encode()).hexdigest(),'adapterSha256':hashlib.sha256(script.encode()).hexdigest(),'applicationDelta':changes,'base':'http://127.0.0.1:'+str(ws['port']),'changes':['Private output directory; same prototype title/date and cover file names using own generated bytes.','Module checks and real service operations unchanged; no response/state substitutions.','Boundary wording identifies 06 own data instead of original 02 workspace.']}
env=os.environ.copy();env.update(H5_CONTENT_BROWSER_URL=meta['base'],H5_CONTENT_BROWSER_ACCOUNT=str(owner))
with (run/'stdout.txt').open('w') as out, (run/'stderr.txt').open('w') as err:
    completed=subprocess.run(['node',str(prepared)],cwd=ROOT,env=env,stdout=out,stderr=err)
meta['exitCode']=completed.returncode
(run/'run.json').write_text(json.dumps(meta,ensure_ascii=False,indent=2)+'\n')
receipt=json.loads((run/'browser.json').read_text()) if (run/'browser.json').exists() else {}
print(json.dumps({'exitCode':completed.returncode,'checks':receipt.get('passed'),'errors':receipt.get('errors'),'evidence':str(run)},ensure_ascii=False))
raise SystemExit(completed.returncode)
