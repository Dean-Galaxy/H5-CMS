<?php

// Generated media and records only in 05's dev.py-bound database. No payment fixtures or remote assets.
use App\Modules\Acquisition\Services\AssetManager;
use App\Modules\Content\Services\ContentManager;
use App\Modules\Content\Services\MediaStore;
use App\Modules\Content\Services\PublicationService;
use App\Modules\Identity\Models\Staff;
use Illuminate\Contracts\Console\Kernel;
use Illuminate\Support\Facades\DB;
use Symfony\Component\Process\Process;

require dirname(__DIR__, 4).'/vendor/autoload.php';
$app = require dirname(__DIR__, 4).'/bootstrap/app.php';
$app->make(Kernel::class)->bootstrap();
$root = realpath(base_path('..'));
$c = json_decode(file_get_contents($root.'/.runtime/workspace.json'), true, flags: JSON_THROW_ON_ERROR);
if (! app()->environment('local') || $c['root'] !== $root || $c['port'] !== 8205 || $c['db_port'] !== 5605 || DB::connection()->getDatabaseName() !== $c['db'] || config('mail.default') !== 'preview'
    || config('acquisition.transport') !== 'disabled' || config('acquisition.external_enabled') || ! config('acquisition.analytics_enabled')) {
    throw new RuntimeException('Only isolated 05 local with external sends disabled.');
}
umask(0077);
$path = $root.'/.runtime/analytics-fixture.json';
if (is_file($path)) {
    echo "Existing isolated analytics fixture retained.\n";
    exit;
}
$account = json_decode(file_get_contents($root.'/.runtime/acquisition-preview-account.json'), true, flags: JSON_THROW_ON_ERROR);
$owner = Staff::where('email', $account['email'])->firstOrFail();
auth('staff')->login($owner);
$s = app('session.store');
$s->start();
$s->put('identity.mfa_staff', $owner->id);
$s->put('identity.version.staff', $owner->session_version);
request()->setLaravelSession($s);
$dir = $root.'/.runtime/analytics-media';
if (! is_dir($dir)) {
    mkdir($dir, 0700, true);
}
foreach ([['-f', 'lavfi', '-i', 'testsrc2=size=144x256:rate=12', '-t', '12', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', $dir.'/analytics-video.mp4'], ['-f', 'lavfi', '-i', 'color=c=teal:s=144x256', '-frames:v', '1', $dir.'/analytics-cover.png']] as $args) {
    $p = new Process([config('content.ffmpeg'), '-nostdin', '-hide_banner', '-loglevel', 'error', '-y', ...$args]);
    $p->setTimeout(60);
    $p->mustRun();
}
$media = app(MediaStore::class);
$assets = [];
foreach (['cover' => 'analytics-cover.png', 'video' => 'analytics-video.mp4'] as $kind => $file) {
    $full = $dir.'/'.$file;
    $asset = $media->start(['kind' => $kind, 'filename' => $file, 'bytes' => filesize($full)]);
    $bytes = file_get_contents($full);
    $media->append($asset->id, 0, $bytes);
    $media->finish($asset->id);
    $asset = $media->process($asset->id);
    if ($asset->state !== 'ready') {
        throw new RuntimeException('Generated media processing failed.');
    }$assets[$kind] = $asset->id;
}
$manager = app(ContentManager::class);
$drama = $manager->saveDrama(['title_en' => '05 Generated Analytics Fixture', 'title_zh' => '05 合成视频埋点验收', 'synopsis_en' => 'Generated local-only test video.', 'synopsis_zh' => '本工作区生成的合成视频，仅用于本站埋点验收。', 'total_episodes' => 1, 'cover_asset_id' => $assets['cover'], 'regions' => ['US'], 'license_from' => now()->subDay()->toIso8601String(), 'license_until' => now()->addYear()->toIso8601String(), 'rights_note' => 'Generated by local ffmpeg testsrc; no third party media.', 'recommended' => true, 'sort_order' => 0, 'category_ids' => []]);
$episode = $manager->saveEpisode($drama->id, ['number' => 1, 'title_en' => 'Local generated episode', 'title_zh' => '合成第1集', 'video_asset_id' => $assets['video']]);
$publication = app(PublicationService::class);
$input = ['mode' => 'completed', 'interval_days' => 1, 'batch_size' => 1];
$preview = $publication->previewLaunchNow($drama->id, $input);
$publication->launchNow($drama->id, $input + ['plan_version' => $preview['plan_version'], 'confirmation' => $preview['confirmation']]);
$links = [];
foreach (['meta', 'tiktok'] as $platform) {
    $assetManager = app(AssetManager::class);
    $pixel = $assetManager->savePixel(null, ['name' => '05 合成埋点 '.$platform, 'platform' => $platform, 'external_id' => $platform === 'meta' ? '123456789098765' : 'TEST_LOCAL_ANALYTICS_05', 'environment' => 'test', 'active' => true, 'version' => 0]);
    $links[$platform] = $assetManager->saveLink(null, ['name' => '05 本地完整链路 '.$platform, 'platform' => $platform, 'drama_id' => $drama->id, 'pixel_id' => $pixel['id'], 'active' => true, 'version' => 0]);
}
file_put_contents($path, json_encode(['drama_id' => $drama->id, 'episode_id' => $episode->id, 'links' => $links, 'generated_only' => true], JSON_PRETTY_PRINT | JSON_THROW_ON_ERROR));
chmod($path,0600);
echo "Own generated video processed/published through Content services; test pixels and links ready. No Billing writes or external calls.\n";
